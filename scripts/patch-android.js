// Apply the Android shell settings after Capacitor creates the native project.
const fs = require("fs");
const path = require("path");

const main = path.join("android", "app", "src", "main");
const manifest = path.join(main, "AndroidManifest.xml");

if (!fs.existsSync(manifest)) {
  throw new Error("AndroidManifest.xml was not generated by Capacitor");
}

let xml = fs.readFileSync(manifest, "utf8");
const permissions = [
  "android.permission.INTERNET",
  "android.permission.ACCESS_NETWORK_STATE",
  "android.permission.RECORD_AUDIO",
  "android.permission.MODIFY_AUDIO_SETTINGS",
  "android.permission.VIBRATE",
  "android.permission.WAKE_LOCK"
];

for (const permission of permissions) {
  if (!xml.includes(permission)) {
    xml = xml.replace(
      "<application",
      `    <uses-permission android:name="${permission}" />\n    <application`
    );
  }
}

if (!xml.includes("android:screenOrientation")) {
  xml = xml.replace(
    "<activity",
    '<activity android:screenOrientation="sensorLandscape"'
  );
}
if (!xml.includes("android:usesCleartextTraffic")) {
  xml = xml.replace(
    "<application",
    '<application android:usesCleartextTraffic="true"'
  );
}

if (!xml.includes("sensorLandscape")) {
  throw new Error("Landscape orientation patch did not apply");
}
fs.writeFileSync(manifest, xml);

const javaDir = path.join(main, "java", "com", "ember", "assistant");
fs.mkdirSync(javaDir, { recursive: true });
fs.writeFileSync(path.join(javaDir, "MainActivity.java"), `package com.ember.assistant;

import android.os.Bundle;
import android.view.WindowManager;
import androidx.core.view.WindowCompat;
import androidx.core.view.WindowInsetsCompat;
import androidx.core.view.WindowInsetsControllerCompat;
import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {
    @Override
    public void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        getWindow().addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);
        applyImmersiveMode();
    }

    @Override
    public void onWindowFocusChanged(boolean hasFocus) {
        super.onWindowFocusChanged(hasFocus);
        if (hasFocus) applyImmersiveMode();
    }

    private void applyImmersiveMode() {
        WindowCompat.setDecorFitsSystemWindows(getWindow(), false);
        WindowInsetsControllerCompat controller =
            WindowCompat.getInsetsController(getWindow(), getWindow().getDecorView());
        controller.hide(WindowInsetsCompat.Type.systemBars());
        controller.setSystemBarsBehavior(
            WindowInsetsControllerCompat.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE
        );
    }
}
`);

console.log("EMBER Android shell patched: landscape + immersive UI.");
